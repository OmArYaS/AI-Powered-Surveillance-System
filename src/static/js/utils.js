const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

function el(tag, props = {}, children = []) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (k === "class") node.className = v;
    else if (k === "html") node.innerHTML = v;
    else if (k === "style" && typeof v === "object") Object.assign(node.style, v);
    else if (k.startsWith("on") && typeof v === "function") {
      node.addEventListener(k.slice(2).toLowerCase(), v);
    } else if (k in node) {
      node[k] = v;
    } else {
      node.setAttribute(k, v);
    }
  }
  for (const c of [].concat(children)) {
    if (c == null) continue;
    node.appendChild(typeof c === "string" ? document.createTextNode(c) : c);
  }
  return node;
}

function icon(name) {
  return ICONS[name] || "";
}

function formatTime(d = new Date()) {
  return d.toLocaleTimeString("en-US", { hour12: false, hour: "2-digit", minute: "2-digit", second: "2-digit" });
}

function formatDate(ts) {
  if (!ts) return "—";
  return new Date(ts * 1000).toLocaleString();
}

// Toast
function ensureToastContainer() {
  let c = document.getElementById("toast-container");
  if (!c) {
    c = el("div", { id: "toast-container", class: "toast-container" });
    document.body.appendChild(c);
  }
  return c;
}

function showToast(message, type = "info", duration = 3000) {
  const c = ensureToastContainer();
  const t = el("div", { class: `toast ${type}` }, [
    el("div", { style: { flex: 1 } }, message),
  ]);
  c.appendChild(t);
  setTimeout(() => {
    t.classList.add("fade-out");
    setTimeout(() => t.remove(), 200);
  }, duration);
}

// Modal
function showModal({ title, text, confirmText = "Confirm", cancelText = "Cancel", danger = false }) {
  return new Promise((resolve) => {
    const backdrop = el("div", { class: "modal-backdrop" });
    const modal = el("div", { class: "modal" }, [
      el("div", { class: "modal-title" }, title),
      el("div", { class: "modal-text" }, text || ""),
      el("div", { class: "modal-actions" }, [
        el("button", { class: "btn btn-ghost", onclick: close.bind(null, false) }, cancelText),
        el("button", { class: `btn ${danger ? "btn-danger" : "btn-primary"}`, onclick: close.bind(null, true) }, confirmText),
      ]),
    ]);
    backdrop.appendChild(modal);
    document.body.appendChild(backdrop);
    function close(result) {
      backdrop.remove();
      resolve(result);
    }
    backdrop.addEventListener("click", (e) => {
      if (e.target === backdrop) close(false);
    });
  });
}

function showPrompt({ title, text, placeholder = "", defaultValue = "" }) {
  return new Promise((resolve) => {
    const backdrop = el("div", { class: "modal-backdrop" });
    let inputVal = defaultValue;
    const input = el("input", {
      class: "form-input",
      type: "text",
      placeholder,
      value: defaultValue,
      oninput: (e) => (inputVal = e.target.value),
    });
    setTimeout(() => input.focus(), 50);

    const modal = el("div", { class: "modal" }, [
      el("div", { class: "modal-title" }, title),
      text ? el("div", { class: "modal-text" }, text) : null,
      el("div", { class: "form-group" }, [input]),
      el("div", { class: "modal-actions" }, [
        el("button", { class: "btn btn-ghost", onclick: close.bind(null, null) }, "Cancel"),
        el("button", { class: "btn btn-primary", onclick: close.bind(null, "_ok_") }, "Confirm"),
      ]),
    ]);
    backdrop.appendChild(modal);
    document.body.appendChild(backdrop);
    function close(result) {
      backdrop.remove();
      resolve(result === "_ok_" ? inputVal.trim() : null);
    }
    input.addEventListener("keydown", (e) => {
      if (e.key === "Enter") close("_ok_");
      if (e.key === "Escape") close(null);
    });
    backdrop.addEventListener("click", (e) => {
      if (e.target === backdrop) close(null);
    });
  });
}
